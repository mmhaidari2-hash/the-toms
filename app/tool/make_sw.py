"""Post-build: write build/web/sw.js precaching every built file (offline PWA)."""
import hashlib, json, os, sys
root = sys.argv[1] if len(sys.argv) > 1 else 'build/web'
files, h = [], hashlib.sha1()
for r, ds, fs in os.walk(root):
    ds[:] = [d for d in ds if not d.startswith('.')]
    for f in sorted(fs):
        p = os.path.relpath(os.path.join(r, f), root).replace(os.sep, '/')
        if p in ('sw.js', 'flutter_service_worker.js') or p.endswith('.map') or f.startswith('.'):
            continue
        files.append(p)
        h.update(p.encode()); h.update(open(os.path.join(r, f), 'rb').read())
ver = h.hexdigest()[:12]
audio = [f for f in files if '/audio/' in f and f.endswith('.mp3')]
files = [f for f in files if f not in audio]
sw = f"""// Generated by tool/make_sw.py — cache-first offline service worker.
const CACHE = 'thetoms-{ver}';
const FILES = {json.dumps(['./'] + files)};
const AUDIO_CACHE = 'thetoms-audio-v1'; // content-addressed clips never go stale: kept across deploys, filled as you play
self.addEventListener('install', e => e.waitUntil(caches.open(CACHE).then(c => Promise.allSettled(FILES.map(f => c.add(f)))).then(() => self.skipWaiting())));
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE && k !== AUDIO_CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
// Voices: cached on first play (and when the app asks to prefetch a lesson), never re-downloaded after a deploy.
async function clip(url) {{
  const c = await caches.open(AUDIO_CACHE);
  let hit = await c.match(url, {{ignoreSearch: true}});
  if (!hit) {{ const res = await fetch(url); if (!res.ok) return res; await c.put(url, res.clone()); hit = res; }}
  return hit;
}}
self.addEventListener('message', e => {{ if (e.data && e.data.prefetch) e.waitUntil(Promise.allSettled(e.data.prefetch.map(u => clip(new URL(u, self.registration.scope).href)))); }});
self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // App code is network-first so a new deploy is never hidden behind a stale cached main.dart.js.
  const path = new URL(req.url).pathname;
  if (req.mode === 'navigate' || /(main\\.dart\\.(js|wasm|mjs)|flutter_bootstrap\\.js|flutter\\.js|index\\.html|version\\.json|manifest\\.json|AssetManifest[^/]*|FontManifest\\.json|index\\.json)$/.test(path) || path.endsWith('/')) {{
    e.respondWith(fetch(req, {{cache: 'no-cache'}}).then(res => {{
      if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }}
      return res;
    }}).catch(() => caches.match(req, {{ignoreSearch: true}}).then(hit => hit || caches.match('./index.html'))));
    return;
  }}
  if (false) {{
    e.respondWith(fetch(req).catch(() => caches.match('./index.html')));
    return;
  }}
  const range = req.headers.get('range');
  if (path.includes('/audio/') && path.endsWith('.mp3')) {{
    // Safari requests media with Range; answer 206 from the cache so offline audio plays.
    e.respondWith(clip(req.url.split('?')[0]).then(async hit => {{
      if (!hit.ok || !range) return hit;
      const buf = await hit.arrayBuffer();
      const m = /bytes=(\\d*)-(\\d*)/.exec(range) || [];
      const start = m[1] ? +m[1] : 0, end = m[2] ? +m[2] : buf.byteLength - 1;
      return new Response(buf.slice(start, end + 1), {{status: 206, headers: {{'Content-Type': 'audio/mpeg', 'Content-Range': `bytes ${{start}}-${{end}}/${{buf.byteLength}}`, 'Content-Length': String(end - start + 1), 'Accept-Ranges': 'bytes'}}}});
    }}));
    return;
  }}
  e.respondWith(caches.match(req, {{ignoreSearch: true}}).then(hit => hit || fetch(req).then(res => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }}
    return res;
  }})));
}});
"""
open(os.path.join(root, 'sw.js'), 'w').write(sw)
print(f'sw.js: {len(files)} precached + {len(audio)} voice clips, cache {ver}')
