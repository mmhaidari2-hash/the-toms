"""Post-build: write build/web/sw.js precaching every built file (offline PWA)."""
import hashlib, json, os, sys
root = sys.argv[1] if len(sys.argv) > 1 else 'build/web'
files, h = [], hashlib.sha1()
for r, ds, fs in os.walk(root):
    ds[:] = [d for d in ds if not d.startswith('.')]
    for f in sorted(fs):
        p = os.path.relpath(os.path.join(r, f), root).replace(os.sep, '/')
        if p in ('sw.js', 'flutter_service_worker.js') or p.endswith('.map') or f.startswith('.'):
            continue
        files.append(p)
        h.update(p.encode()); h.update(open(os.path.join(r, f), 'rb').read())
ver = h.hexdigest()[:12]
audio = [f for f in files if '/audio/' in f and f.endswith('.mp3')]
# Clips are keyed by speaker|text, not by voice: a re-voiced clip keeps its URL. So the audio cache is named after
# the cast (voice manifest) and every clip's size; any re-render or re-voice gives a new name and old clips are dropped.
def audio_version(root, audio):
    a = hashlib.sha1()
    man = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'audit', 'voice_manifest.json')
    if os.path.exists(man): a.update(open(man, 'rb').read())
    for f in sorted(audio): a.update(f.encode()); a.update(str(os.path.getsize(os.path.join(root, f))).encode())
    return a.hexdigest()[:10]
aver = audio_version(root, audio)
files = [f for f in files if f not in audio]
# Helper-language tables (several MB each) load only when that language is picked; cached on first use.
files = [f for f in files if '/assets/i18n/' not in '/' + f]
sw = f"""// Generated by tool/make_sw.py — cache-first offline service worker.
const CACHE = 'thetoms-{ver}';
const FILES = {json.dumps(['./'] + files)};
const AUDIO_CACHE = 'thetoms-audio-{aver}'; // from the voice manifest + clip sizes: changes whenever any clip is re-voiced or re-rendered (old audio caches are deleted on activate)
self.addEventListener('install', e => e.waitUntil(caches.open(CACHE).then(c => Promise.allSettled(FILES.map(f => c.add(f)))).then(() => self.skipWaiting())));
// Every deploy gets a new CACHE name; on activate every other cache (old versions, Flutter's own) is deleted.
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE && k !== AUDIO_CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
// Voices: cached on first play (and when the app asks to prefetch a lesson); re-downloaded only when the audio version changes.
async function clip(url) {{
  const c = await caches.open(AUDIO_CACHE);
  let hit = await c.match(url, {{ignoreSearch: true}});
  if (!hit) {{ const res = await fetch(url, {{cache: 'no-cache'}}); if (!res.ok) return res; await c.put(url, res.clone()); hit = res; }}
  return hit;
}}
self.addEventListener('message', e => {{ if (e.data && e.data.prefetch) e.waitUntil(Promise.allSettled(e.data.prefetch.map(u => clip(new URL(u, self.registration.scope).href)))); }});
self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // App code is network-first so a new deploy is never hidden behind a stale cached main.dart.js.
  const path = new URL(req.url).pathname;
  if (req.mode === 'navigate' || /(main\\.dart\\.(js|wasm|mjs)|flutter_bootstrap\\.js|flutter\\.js|index\\.html|version\\.json|manifest\\.json|AssetManifest[^/]*|FontManifest\\.json|index\\.json)$/.test(path) || path.endsWith('/')) {{
    e.respondWith(fetch(req, {{cache: 'no-cache'}}).then(res => {{
      if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }}
      return res;
    }}).catch(() => caches.match(req, {{ignoreSearch: true}}).then(hit => hit || caches.match('./index.html'))));
    return;
  }}
  if (false) {{
    e.respondWith(fetch(req).catch(() => caches.match('./index.html')));
    return;
  }}
  const range = req.headers.get('range');
  if (path.includes('/audio/') && path.endsWith('.mp3')) {{
    // Safari requests media with Range; answer 206 from the cache so offline audio plays.
    e.respondWith(clip(req.url.split('?')[0]).then(async hit => {{
      if (!hit.ok || !range) return hit;
      const buf = await hit.arrayBuffer();
      const m = /bytes=(\\d*)-(\\d*)/.exec(range) || [];
      const start = m[1] ? +m[1] : 0, end = m[2] ? +m[2] : buf.byteLength - 1;
      return new Response(buf.slice(start, end + 1), {{status: 206, headers: {{'Content-Type': 'audio/mpeg', 'Content-Range': `bytes ${{start}}-${{end}}/${{buf.byteLength}}`, 'Content-Length': String(end - start + 1), 'Accept-Ranges': 'bytes'}}}});
    }}));
    return;
  }}
  // Pictures: cache-first, but a cached entry that isn't a real image (old/broken caches, notably on iOS
  // home-screen apps) is thrown away and fetched fresh, bypassing the HTTP cache.
  if (/\\.(webp|png|jpe?g|svg|gif)$/i.test(path)) {{
    e.respondWith(caches.open(CACHE).then(async c => {{
      const hit = await c.match(req, {{ignoreSearch: true}});
      const good = r => r && r.ok && r.status === 200 && /^image\\//.test(r.headers.get('content-type') || '');
      if (good(hit)) return hit;
      if (hit) await c.delete(req, {{ignoreSearch: true}});
      try {{
        const res = await fetch(req.url.split('?')[0] + '?v=' + CACHE, {{cache: 'reload'}});
        if (good(res)) await c.put(req.url.split('?')[0], res.clone());
        return res;
      }} catch (err) {{ return hit || Response.error(); }}
    }}));
    return;
  }}
  e.respondWith(caches.match(req, {{ignoreSearch: true}}).then(hit => hit || fetch(req).then(res => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }}
    return res;
  }})));
}});
"""

# Android + web share this version so a re-voice busts every cache.
ver_path = os.path.join(root, 'assets', 'assets', 'audio', 'ver.json')
os.makedirs(os.path.dirname(ver_path), exist_ok=True)
open(ver_path, 'w').write(json.dumps({'v': aver}))
# Also refresh the Dart constant used by the Android player.
dart = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lib', 'core', 'platform', 'audio_ver.g.dart')
open(dart, 'w').write("// Generated by tool/make_sw.py\nconst String kAudioCacheVer = '%s';\n" % aver)
# And the source asset copy used by the next APK build.
src_ver = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets', 'audio', 'ver.json')
open(src_ver, 'w').write(json.dumps({'v': aver}))

open(os.path.join(root, 'sw.js'), 'w').write(sw)
print(f'sw.js: {len(files)} precached + {len(audio)} voice clips, cache {ver}, audio cache {aver}')
