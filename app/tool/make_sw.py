"""Generate the scoped offline worker after a Flutter web build.

The audio cache name is derived from the source audio pack (voice_manifest +
every source mp3), using the same path names a Flutter web build would
(`assets/assets/audio/...`). It is never taken from the (often incomplete)
set of clips copied into a given web build, so ver.json, audio_ver.g.dart and
sw.js cannot drift apart. Use --sync-source-ver to refresh the source files
without a web build, and --check-source-ver to fail if they are stale.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path


TOOL = Path(__file__).resolve().parent
APP = TOOL.parent
# Path names hashed into the audio version must match a Flutter web build, so
# a published ver.json (e.g. 4ca397102f) stays identical to kAudioCacheVer.
WEB_AUDIO_NAME_PREFIX = "assets/assets/audio/"


def audio_version_from_files(named_files):
    """Content, not just file size: same-sized re-voices must invalidate audio."""
    digest = hashlib.sha256()
    manifest = TOOL / "audit" / "voice_manifest.json"
    if manifest.exists():
        digest.update(manifest.read_bytes())
    for name, path in sorted(named_files, key=lambda item: item[0]):
        digest.update(name.encode())
        digest.update(Path(path).read_bytes())
    return digest.hexdigest()[:10]


def audio_version(root, audio):
    root = Path(root)
    return audio_version_from_files((name, root / name) for name in audio)


def source_mp3_files():
    return sorted((APP / "assets" / "audio").glob("*.mp3"))


def source_pack_complete():
    index = APP / "assets" / "audio" / "index.json"
    if not index.is_file():
        return False
    ids = json.loads(index.read_text())
    if not isinstance(ids, list):
        return False
    return len(source_mp3_files()) >= len(ids)


def source_audio_version():
    return audio_version_from_files(
        (f"{WEB_AUDIO_NAME_PREFIX}{p.name}", p) for p in source_mp3_files()
    )


def committed_audio_version():
    return json.loads((APP / "assets" / "audio" / "ver.json").read_text())["v"]


def write_source_audio_ver(aver):
    version = json.dumps({"v": aver})
    (APP / "assets" / "audio" / "ver.json").write_text(version)
    (APP / "lib" / "core" / "platform" / "audio_ver.g.dart").write_text(
        "// Generated by tool/make_sw.py\n"
        f"const String kAudioCacheVer = '{aver}';\n"
    )
    return aver


def resolve_audio_version(sync_source=True):
    """Audio cache name always comes from the source pack, not a web-build subset."""
    if source_pack_complete():
        aver = source_audio_version()
        if sync_source:
            write_source_audio_ver(aver)
        return aver
    return committed_audio_version()


def check_source_audio_ver():
    dart = (APP / "lib" / "core" / "platform" / "audio_ver.g.dart").read_text()
    ver = committed_audio_version()
    match = re.search(r"kAudioCacheVer = '([^']*)'", dart)
    dart_ver = match.group(1) if match else None
    if dart_ver != ver:
        raise SystemExit(f"ver.json ({ver}) != audio_ver.g.dart ({dart_ver})")
    if not source_pack_complete():
        raise SystemExit(
            f"source audio pack is incomplete; cannot verify {ver} against content"
        )
    computed = source_audio_version()
    if computed != ver:
        raise SystemExit(f"stale audio version {ver}; source pack is {computed}")
    print(f"audio ver {ver} ok")


def generate(root, sync_source=True):
    root = Path(root).resolve()
    if not (root / "index.html").is_file() or not (root / "main.dart.js").is_file():
        raise ValueError("Expected a completed Flutter JavaScript web build")
    files = sorted(
        p.relative_to(root).as_posix()
        for p in root.rglob("*")
        if p.is_file()
        and not any(part.startswith(".") for part in p.relative_to(root).parts)
    )
    audio = [f for f in files if "/audio/" in f and f.endswith(".mp3")]
    aver = resolve_audio_version(sync_source=sync_source)
    version = json.dumps({"v": aver})
    ver_path = root / "assets" / "assets" / "audio" / "ver.json"
    ver_path.parent.mkdir(parents=True, exist_ok=True)
    ver_path.write_text(version)
    # The loader explicitly selects CanvasKit. Do not download unused skwasm
    # variants or debugging symbols on every phone. Languages/voices cache on use.
    files = [
        f for f in files
        if f not in ("sw.js", "flutter_service_worker.js")
        and not f.endswith((".map", ".symbols"))
        and not ("/audio/" in f and f.endswith(".mp3"))
        and "/assets/i18n/" not in "/" + f
        and not Path(f).name.startswith("skwasm")
    ]
    ver_name = ver_path.relative_to(root).as_posix()
    if ver_name not in files:
        files.append(ver_name)
        files.sort()
    template = (TOOL / "service_worker.js").read_text()
    digest = hashlib.sha256(template.encode())
    for f in files:
        digest.update(f.encode())
        digest.update((root / f).read_bytes())
    ver = digest.hexdigest()[:12]
    worker = (template.replace("__CACHE_VERSION__", ver)
              .replace("__AUDIO_VERSION__", aver)
              .replace("__PRECACHE_FILES__", json.dumps(["./"] + files)))
    (root / "sw.js").write_text(worker)
    print(f"sw.js: {len(files)} required resources, {len(audio)} lazy audio clips; "
          f"shell {ver}, audio {aver}")
    return files


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", default="build/web")
    parser.add_argument("--no-sync-source", action="store_true")
    parser.add_argument(
        "--sync-source-ver",
        action="store_true",
        help="Update ver.json and audio_ver.g.dart from the source pack; no web build needed",
    )
    parser.add_argument(
        "--check-source-ver",
        action="store_true",
        help="Fail if ver.json / audio_ver.g.dart disagree with the source pack",
    )
    args = parser.parse_args()
    if args.check_source_ver:
        check_source_audio_ver()
    elif args.sync_source_ver:
        if not source_pack_complete():
            raise SystemExit("source audio pack is incomplete; refusing to rewrite ver.json")
        aver = write_source_audio_ver(source_audio_version())
        print(f"source audio ver {aver}")
    else:
        generate(args.root, sync_source=not args.no_sync_source)
