"""Generate the scoped offline worker after a Flutter web build."""
import argparse
import hashlib
import json
import os
from pathlib import Path


TOOL = Path(__file__).resolve().parent
APP = TOOL.parent


def audio_version(root, audio):
    """Content, not just file size: same-sized re-voices must invalidate audio."""
    digest = hashlib.sha256()
    manifest = TOOL / "audit" / "voice_manifest.json"
    if manifest.exists():
        digest.update(manifest.read_bytes())
    for name in sorted(audio):
        digest.update(name.encode())
        digest.update((Path(root) / name).read_bytes())
    return digest.hexdigest()[:10]


def generate(root, sync_source=True):
    root = Path(root).resolve()
    if not (root / "index.html").is_file() or not (root / "main.dart.js").is_file():
        raise ValueError("Expected a completed Flutter JavaScript web build")
    files = sorted(
        p.relative_to(root).as_posix()
        for p in root.rglob("*")
        if p.is_file()
        and not any(part.startswith(".") for part in p.relative_to(root).parts)
    )
    audio = [f for f in files if "/audio/" in f and f.endswith(".mp3")]
    aver = audio_version(root, audio)
    version = json.dumps({"v": aver})
    ver_path = root / "assets" / "assets" / "audio" / "ver.json"
    ver_path.parent.mkdir(parents=True, exist_ok=True)
    ver_path.write_text(version)
    if sync_source:
        (APP / "assets" / "audio" / "ver.json").write_text(version)
        (APP / "lib" / "core" / "platform" / "audio_ver.g.dart").write_text(
            "// Generated by tool/make_sw.py\n"
            f"const String kAudioCacheVer = '{aver}';\n"
        )
    # The loader explicitly selects CanvasKit. Do not download unused skwasm
    # variants or debugging symbols on every phone. Languages/voices cache on use.
    files = [
        f for f in files
        if f not in ("sw.js", "flutter_service_worker.js")
        and not f.endswith((".map", ".symbols"))
        and not ("/audio/" in f and f.endswith(".mp3"))
        and "/assets/i18n/" not in "/" + f
        and not Path(f).name.startswith("skwasm")
    ]
    ver_name = ver_path.relative_to(root).as_posix()
    if ver_name not in files:
        files.append(ver_name)
        files.sort()
    template = (TOOL / "service_worker.js").read_text()
    digest = hashlib.sha256(template.encode())
    for f in files:
        digest.update(f.encode())
        digest.update((root / f).read_bytes())
    ver = digest.hexdigest()[:12]
    worker = (template.replace("__CACHE_VERSION__", ver)
              .replace("__AUDIO_VERSION__", aver)
              .replace("__PRECACHE_FILES__", json.dumps(["./"] + files)))
    (root / "sw.js").write_text(worker)
    print(f"sw.js: {len(files)} required resources, {len(audio)} lazy audio clips; "
          f"shell {ver}, audio {aver}")
    return files


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", default="build/web")
    parser.add_argument("--no-sync-source", action="store_true")
    args = parser.parse_args()
    generate(args.root, sync_source=not args.no_sync_source)
